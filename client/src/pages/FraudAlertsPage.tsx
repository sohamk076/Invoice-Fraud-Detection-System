import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { PageHeader } from '../components/layout/PageHeader';
import { RiskBadge } from '../components/common/RiskBadge';
import { StatusBadge } from '../components/common/StatusBadge';
import { LoadingSpinner } from '../components/common/LoadingSpinner';
import { EmptyState } from '../components/common/EmptyState';
import { Modal } from '../components/common/Modal';
import { fraudService } from '../services/fraud.service';
import { useToast } from '../context/ToastContext';
import { useAuth } from '../context/AuthContext';
import { FraudAlert, AlertStatus } from '../types';
import { formatINR, formatDateIndian, formatDateTimeIndian } from '../utils/formatters';
import {
  AlertTriangle,
  AlertOctagon,
  ShieldCheck,
  CheckCircle,
  XCircle,
  UserCheck,
  ChevronRight,
  ArrowRight,
  Filter,
  FileText,
  Clock,
  Eye,
  ShieldAlert,
  Search,
  Building2,
  ExternalLink,
} from 'lucide-react';

export const FraudAlertsPage: React.FC = () => {
  const toast = useToast();
  const { user, hasRole } = useAuth();

  const [alerts, setAlerts] = useState<FraudAlert[]>([]);
  const [activeStatusTab, setActiveStatusTab] = useState<string>('ALL');
  const [severityFilter, setSeverityFilter] = useState<string>('');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [isLoading, setIsLoading] = useState<boolean>(true);

  // Resolution / Action Modal State
  const [selectedAlert, setSelectedAlert] = useState<FraudAlert | null>(null);
  const [targetAction, setTargetAction] = useState<AlertStatus | 'ASSIGN' | null>(null);
  const [resolutionNotes, setResolutionNotes] = useState<string>('');
  const [isSubmitting, setIsSubmitting] = useState<boolean>(false);

  // Full Forensic Inspection Modal State
  const [inspectAlert, setInspectAlert] = useState<FraudAlert | null>(null);

  const fetchAlerts = async () => {
    try {
      setIsLoading(true);
      const res = await fraudService.getAlerts({
        status: activeStatusTab === 'ALL' ? undefined : activeStatusTab,
        severity: severityFilter || undefined,
        limit: 50,
      });
      setAlerts(res.data);
    } catch (err) {
      toast.error('Failed to load fraud alerts.');
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, [activeStatusTab, severityFilter]);

  const handleOpenActionModal = (alert: FraudAlert, action: AlertStatus | 'ASSIGN') => {
    setSelectedAlert(alert);
    setTargetAction(action);
    setResolutionNotes(alert.resolutionNotes || '');
  };

  const handleExecuteAlertAction = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedAlert || !targetAction) return;

    try {
      setIsSubmitting(true);
      let payload: any = { resolutionNotes };

      if (targetAction === 'ASSIGN') {
        payload.assignedToId = user?.id;
        payload.status = 'IN_REVIEW';
      } else {
        payload.status = targetAction;
        if (!selectedAlert.assignedToId && user?.id) {
          payload.assignedToId = user.id;
        }
      }

      await fraudService.updateAlert(selectedAlert.id, payload);
      toast.success(`Alert updated to "${payload.status}".`);
      setSelectedAlert(null);
      setTargetAction(null);
      if (inspectAlert && inspectAlert.id === selectedAlert.id) {
        setInspectAlert(null);
      }
      fetchAlerts();
    } catch (err: any) {
      toast.error(err.response?.data?.message || 'Failed to update alert.');
    } finally {
      setIsSubmitting(false);
    }
  };

  const isAuditorOrAdmin = hasRole(['ADMIN', 'AUDITOR']);

  const filteredAlerts = alerts.filter((alert) => {
    if (!searchQuery) return true;
    const q = searchQuery.toLowerCase();
    return (
      alert.title.toLowerCase().includes(q) ||
      alert.description.toLowerCase().includes(q) ||
      alert.invoice?.invoiceNumber.toLowerCase().includes(q) ||
      alert.invoice?.vendor?.name.toLowerCase().includes(q) ||
      alert.alertType.toLowerCase().includes(q)
    );
  });

  return (
    <div className="space-y-6">
      <PageHeader
        title="Fraud Alert Center & Forensic Review"
        subtitle="Active compliance alerts generated by deterministic rule breaches, transaction spikes, and GST discrepancies"
        breadcrumbs={[{ label: 'Fraud Alerts' }]}
      />

      {/* Control Bar: Status Tabs, Severity Filter & Search */}
      <div className="flex flex-col md:flex-row items-center justify-between gap-3 bg-slate-900 border border-slate-800 p-4 rounded-3xl shadow-sm">
        {/* Status Tabs */}
        <div className="flex flex-wrap items-center gap-1.5 w-full md:w-auto">
          {[
            { label: 'All Alerts', val: 'ALL' },
            { label: 'Open', val: 'OPEN' },
            { label: 'In Review', val: 'IN_REVIEW' },
            { label: 'Resolved', val: 'RESOLVED' },
            { label: 'Dismissed', val: 'DISMISSED' },
          ].map((tab) => {
            const count =
              tab.val === 'ALL'
                ? alerts.length
                : alerts.filter((a) => a.status === tab.val).length;

            return (
              <button
                key={tab.val}
                onClick={() => setActiveStatusTab(tab.val)}
                className={`px-3.5 py-1.5 rounded-xl text-xs font-semibold transition-all flex items-center gap-1.5 ${
                  activeStatusTab === tab.val
                    ? 'bg-blue-600 text-white shadow-md'
                    : 'bg-slate-950 text-slate-400 hover:text-slate-200 hover:bg-slate-800'
                }`}
              >
                <span>{tab.label}</span>
                <span
                  className={`text-[10px] font-mono px-1.5 py-0.2 rounded-full ${
                    activeStatusTab === tab.val
                      ? 'bg-blue-700 text-white'
                      : 'bg-slate-900 text-slate-400'
                  }`}
                >
                  {count}
                </span>
              </button>
            );
          })}
        </div>

        {/* Severity Filter & Search */}
        <div className="flex items-center gap-2 w-full md:w-auto">
          <select
            value={severityFilter}
            onChange={(e) => setSeverityFilter(e.target.value)}
            className="px-3 py-2 bg-slate-950 border border-slate-800 rounded-xl text-xs text-slate-200 focus:outline-none focus:border-blue-500"
          >
            <option value="">All Severities</option>
            <option value="CRITICAL">Critical (75-100)</option>
            <option value="HIGH">High (50-74)</option>
            <option value="MEDIUM">Medium (25-49)</option>
            <option value="LOW">Low (0-24)</option>
          </select>

          <div className="relative flex-1 md:w-56">
            <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 transform -translate-y-1/2 text-slate-500" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search alerts..."
              className="w-full pl-8 pr-3 py-2 bg-slate-950 border border-slate-800 rounded-xl text-xs text-slate-200 placeholder-slate-500 focus:outline-none focus:border-blue-500"
            />
          </div>
        </div>
      </div>

      {/* Alerts Feed Cards / Table */}
      {isLoading ? (
        <LoadingSpinner fullHeight label="Scanning forensic alert database..." />
      ) : filteredAlerts.length > 0 ? (
        <div className="space-y-4">
          {filteredAlerts.map((alert) => {
            const isCritical = alert.severity === 'CRITICAL';
            const isResolved = alert.status === 'RESOLVED' || alert.status === 'DISMISSED';

            const cardBorder = isCritical
              ? 'border-red-900/60 bg-gradient-to-r from-red-950/30 via-slate-900 to-slate-900'
              : 'border-slate-800 bg-slate-900';

            return (
              <div
                key={alert.id}
                className={`p-5 sm:p-6 rounded-3xl border shadow-md space-y-4 transition-all hover:border-slate-750 ${cardBorder}`}
              >
                <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4">
                  {/* Left: Icon & Alert Overview */}
                  <div className="flex items-start gap-4">
                    <div className="p-3 rounded-2xl bg-slate-950/80 border border-slate-800 shrink-0 mt-0.5">
                      {isCritical ? (
                        <AlertOctagon className="w-5 h-5 text-red-400 animate-pulse" />
                      ) : (
                        <AlertTriangle className="w-5 h-5 text-orange-400" />
                      )}
                    </div>

                    <div className="space-y-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <span className="text-[11px] font-bold uppercase tracking-wider px-2.5 py-0.5 rounded-full bg-slate-950 border border-slate-800 font-mono text-blue-400">
                          {alert.alertType}
                        </span>
                        <h4 className="text-sm font-bold text-white tracking-tight">{alert.title}</h4>
                        <RiskBadge level={alert.severity} size="sm" />
                        <StatusBadge status={alert.status} size="sm" />
                      </div>

                      <p className="text-xs text-slate-300 leading-relaxed max-w-3xl font-medium">
                        {alert.description}
                      </p>

                      <div className="flex flex-wrap items-center gap-3 pt-1 text-[11px] text-slate-400 font-sans">
                        <span className="flex items-center gap-1 font-mono">
                          <Clock className="w-3 h-3 text-slate-500" />
                          {formatDateTimeIndian(alert.createdAt)}
                        </span>
                        <span>•</span>
                        <span className="flex items-center gap-1">
                          <UserCheck className="w-3 h-3 text-slate-500" />
                          Auditor: <strong className="text-slate-200">{alert.assignedTo?.name || 'Unassigned (Queue)'}</strong>
                        </span>
                        {alert.resolutionNotes && (
                          <>
                            <span>•</span>
                            <span className="text-slate-300 italic">
                              Notes: "{alert.resolutionNotes}"
                            </span>
                          </>
                        )}
                      </div>
                    </div>
                  </div>

                  {/* Right: Invoice Summary & Action Buttons */}
                  <div className="flex flex-col sm:flex-row lg:flex-col items-start lg:items-end justify-between gap-3 shrink-0 pt-2 lg:pt-0 border-t lg:border-t-0 border-slate-800">
                    {alert.invoice && (
                      <div className="text-left lg:text-right text-xs">
                        <Link
                          to={`/invoices/${alert.invoice.id}`}
                          className="font-mono font-bold text-blue-400 hover:text-blue-300 flex items-center lg:justify-end gap-1"
                        >
                          <span>{alert.invoice.invoiceNumber}</span>
                          <ExternalLink className="w-3 h-3" />
                        </Link>
                        <div className="text-slate-300 font-semibold">{alert.invoice.vendor?.name}</div>
                        <div className="font-mono font-extrabold text-slate-100 text-sm">
                          {formatINR(alert.invoice.grandTotal)}
                        </div>
                      </div>
                    )}

                    <div className="flex flex-wrap items-center gap-2 pt-1">
                      <button
                        onClick={() => setInspectAlert(alert)}
                        className="px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold rounded-xl border border-slate-700 transition-colors flex items-center gap-1"
                      >
                        <Eye className="w-3.5 h-3.5 text-blue-400" />
                        <span>Inspect</span>
                      </button>

                      {isAuditorOrAdmin && !isResolved && (
                        <>
                          {alert.status === 'OPEN' && (
                            <button
                              onClick={() => handleOpenActionModal(alert, 'ASSIGN')}
                              className="px-3 py-1.5 bg-blue-600 hover:bg-blue-500 text-white text-xs font-semibold rounded-xl shadow transition-colors flex items-center gap-1"
                            >
                              <UserCheck className="w-3.5 h-3.5" />
                              <span>Start Review</span>
                            </button>
                          )}

                          <button
                            onClick={() => handleOpenActionModal(alert, 'RESOLVED')}
                            className="px-3 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold rounded-xl shadow transition-colors flex items-center gap-1"
                          >
                            <CheckCircle className="w-3.5 h-3.5" />
                            <span>Resolve</span>
                          </button>

                          <button
                            onClick={() => handleOpenActionModal(alert, 'DISMISSED')}
                            className="px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-slate-200 text-xs font-semibold rounded-xl border border-slate-700 transition-colors flex items-center gap-1"
                          >
                            <XCircle className="w-3.5 h-3.5" />
                            <span>Dismiss</span>
                          </button>
                        </>
                      )}
                    </div>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        <EmptyState
          title="No Fraud Alerts Found"
          description="There are currently no active alerts matching the selected filter criteria."
          icon={<ShieldCheck className="w-12 h-12 text-emerald-400" />}
        />
      )}

      {/* Section 7: Detailed Forensic Alert Inspection Modal */}
      <Modal
        isOpen={Boolean(inspectAlert)}
        onClose={() => setInspectAlert(null)}
        title={`Forensic Alert Review: ${inspectAlert?.title}`}
        size="lg"
      >
        {inspectAlert && (
          <div className="space-y-5 text-xs">
            {/* Alert Summary Header */}
            <div className="p-4 bg-slate-950 rounded-2xl border border-slate-800 space-y-2">
              <div className="flex items-center justify-between">
                <span className="font-mono text-blue-400 font-bold uppercase">{inspectAlert.alertType}</span>
                <div className="flex items-center gap-2">
                  <RiskBadge level={inspectAlert.severity} size="sm" />
                  <StatusBadge status={inspectAlert.status} size="sm" />
                </div>
              </div>
              <p className="text-slate-200 font-medium text-xs leading-relaxed">{inspectAlert.description}</p>
              <div className="text-[11px] text-slate-400 font-mono pt-1">
                Triggered on {formatDateTimeIndian(inspectAlert.createdAt)} • Assigned: {inspectAlert.assignedTo?.name || 'Unassigned'}
              </div>
            </div>

            {/* Linked Invoice Info */}
            {inspectAlert.invoice && (
              <div className="p-4 bg-slate-950 rounded-2xl border border-slate-800 space-y-3">
                <div className="flex items-center justify-between border-b border-slate-800 pb-2">
                  <h5 className="font-bold text-white flex items-center gap-1.5">
                    <FileText className="w-4 h-4 text-blue-400" />
                    Target Invoice Intelligence
                  </h5>
                  <Link
                    to={`/invoices/${inspectAlert.invoice.id}`}
                    className="text-blue-400 hover:text-blue-300 font-semibold flex items-center gap-1"
                  >
                    <span>Open Full Inspector</span>
                    <ArrowRight className="w-3 h-3" />
                  </Link>
                </div>

                <div className="grid grid-cols-2 sm:grid-cols-3 gap-3">
                  <div>
                    <span className="text-slate-400 block">Invoice #:</span>
                    <span className="font-mono font-bold text-white">{inspectAlert.invoice.invoiceNumber}</span>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Vendor:</span>
                    <span className="font-bold text-blue-400">{inspectAlert.invoice.vendor?.name}</span>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Grand Total:</span>
                    <span className="font-mono font-bold text-emerald-400">{formatINR(inspectAlert.invoice.grandTotal)}</span>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Fraud Score:</span>
                    <span className="font-mono font-bold text-red-400 text-sm">{inspectAlert.invoice.fraudScore}/100</span>
                  </div>
                  <div>
                    <span className="text-slate-400 block">Invoice Status:</span>
                    <StatusBadge status={inspectAlert.invoice.status} size="sm" />
                  </div>
                </div>
              </div>
            )}

            {/* Quick Action Footer in Inspection Modal */}
            <div className="flex flex-wrap items-center justify-between gap-3 pt-2 border-t border-slate-800">
              <span className="text-slate-400 font-sans text-[11px]">
                {inspectAlert.resolutionNotes ? `Resolution Notes: "${inspectAlert.resolutionNotes}"` : 'No resolution notes recorded.'}
              </span>

              <div className="flex items-center gap-2">
                {inspectAlert.status !== 'RESOLVED' && isAuditorOrAdmin && (
                  <button
                    onClick={() => {
                      setSelectedAlert(inspectAlert);
                      setTargetAction('RESOLVED');
                      setResolutionNotes(inspectAlert.resolutionNotes || '');
                    }}
                    className="px-3.5 py-1.5 bg-emerald-600 hover:bg-emerald-500 text-white font-semibold rounded-xl shadow transition-colors"
                  >
                    Mark Resolved
                  </button>
                )}
                <button
                  onClick={() => setInspectAlert(null)}
                  className="px-3.5 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-300 font-semibold rounded-xl transition-colors"
                >
                  Close
                </button>
              </div>
            </div>
          </div>
        )}
      </Modal>

      {/* Action Confirmation Modal (Resolve, Assign, Dismiss) */}
      <Modal
        isOpen={Boolean(selectedAlert && targetAction)}
        onClose={() => {
          setSelectedAlert(null);
          setTargetAction(null);
        }}
        title={`Audit Action: Update Alert Status`}
      >
        <form onSubmit={handleExecuteAlertAction} className="space-y-4 text-xs">
          <div className="p-3.5 bg-slate-950 rounded-xl border border-slate-800 text-slate-300">
            Updating fraud alert <strong className="text-white">"{selectedAlert?.title}"</strong> to status <strong className="text-blue-400">{targetAction === 'ASSIGN' ? 'IN_REVIEW' : targetAction}</strong>.
          </div>

          <div>
            <label className="block font-semibold text-slate-300 uppercase mb-1.5">
              Auditor Resolution Notes / Forensic Action Taken *
            </label>
            <textarea
              value={resolutionNotes}
              onChange={(e) => setResolutionNotes(e.target.value)}
              required
              rows={3}
              placeholder="e.g. Cross-verified with vendor GST returns, physical inspection confirmed, or cleared after compliance review."
              className="w-full p-3 bg-slate-950 border border-slate-800 rounded-xl text-slate-200 focus:outline-none focus:border-blue-500"
            />
          </div>

          <div className="flex justify-end gap-2 pt-2">
            <button
              type="button"
              onClick={() => {
                setSelectedAlert(null);
                setTargetAction(null);
              }}
              className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-300 font-semibold rounded-xl transition-colors"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="px-4 py-2 bg-blue-600 hover:bg-blue-500 disabled:opacity-50 text-white font-semibold rounded-xl shadow-md transition-colors"
            >
              {isSubmitting ? 'Recording Audit...' : 'Confirm Action'}
            </button>
          </div>
        </form>
      </Modal>
    </div>
  );
};
